"""Общие части живых проверок: безопасные литералы, стадии и чтение регистра БСП."""

import json
import re
from collections.abc import Callable
from typing import Any

from bsp_load import DataServer, ExchangeCheckError, bsl, guarded, short_error


def literal(value: str) -> str:
    """Сохраняет переводы строк значений, не оставляя их в исполняемом коде."""
    parts = re.split(r"([\r\n])", value)
    return (
        "("
        + " + ".join(
            "Символ(13)" if part == "\r" else "Символ(10)" if part == "\n" else bsl(part)
            for part in parts
        )
        + ")"
    )


def text_line(value: object) -> str:
    """Одно значение протокола без внедрения новых строк."""
    return str(value).replace("\r", " ").replace("\n", " | ")


def stage[T](lines: list[str], label: str, action: Callable[[], T]) -> T:
    """Ошибка останавливает сценарий; последующие стадии не получают ложный успех."""
    try:
        result = action()
    except Exception as error:
        lines.append(f"{label} ОШИБКА {short_error(str(error))}")
        raise
    lines.append(f"{label} OK")
    return result


def json_code(body: str, value: str = "Данные") -> str:
    """Ответ `OK` и JSON: строки и сведения о правилах могут содержать разделители."""
    return guarded(
        body
        + f""" Запись = Новый ЗаписьJSON; Запись.УстановитьСтроку();
        ЗаписатьJSON(Запись, {value}); Результат = "OK " + Запись.Закрыть();"""
    )


def read_json(server: DataServer, code: str) -> Any:
    """Пустой, оборванный или не-JSON ответ не является успешным результатом."""
    return json.loads(server.run(code))


def object_body(full_name: str, ref: str, *, required: bool = True) -> str:
    """Разрешает только ссылочные объекты с пометкой удаления, без произвольного кода."""
    # БСП: ОбщегоНазначения:3989 — МенеджерОбъектаПоПолномуИмени.
    # БСП: КонвертацияОбъектовИнформационныхБаз:16597 — ПолучитьОбъект;
    # 8104–8109 — стандартный реквизит ПометкаУдаления.
    check = 'Если О = Неопределено Тогда ВызватьИсключение "Нет объекта"; КонецЕсли;'
    return f"""МД = Метаданные.НайтиПоПолномуИмени({literal(full_name)});
        Если МД = Неопределено Тогда ВызватьИсключение "Нет метаданных объекта"; КонецЕсли;
        ЕстьПометка = Ложь;
        Для Каждого СР Из МД.СтандартныеРеквизиты Цикл
        Если СР.Имя = "ПометкаУдаления" Тогда ЕстьПометка = Истина; КонецЕсли; КонецЦикла;
        Если Не ЕстьПометка Тогда
        ВызватьИсключение "Требуется ссылочный объект с пометкой удаления"; КонецЕсли;
        Ссылка = ОбщегоНазначения.МенеджерОбъектаПоПолномуИмени(МД.ПолноеИмя())
        .ПолучитьСсылку(Новый УникальныйИдентификатор({literal(ref)}));
        О = Ссылка.ПолучитьОбъект(); {check if required else ""}"""


def rule_record_body(plan: str, kind: str) -> str:
    """Две записи регистра: корреспондент хранится в записи конвертации."""
    # БСП: ПравилаДляОбменаДанными.xml:9 — менеджер регистра ПравилаДляОбменаДанными.
    # БСП: ПравилаДляОбменаДанными/ManagerModule:207–221, 276–285 —
    # регистр, ИмяПланаОбмена, ВидПравил, ВидыПравилДляОбменаДанными,
    # ПравилаКонвертацииОбъектов / ПравилаРегистрацииОбъектов.
    if kind not in ("exchange", "correspondent", "registration"):
        raise ValueError("неизвестный вид правил")
    enum = "ПравилаРегистрацииОбъектов" if kind == "registration" else "ПравилаКонвертацииОбъектов"
    return f"""З = РегистрыСведений.ПравилаДляОбменаДанными.СоздатьМенеджерЗаписи();
        З.ИмяПланаОбмена = {literal(plan)};
        З.ВидПравил = Перечисления.ВидыПравилДляОбменаДанными.{enum}; З.Прочитать();"""


def rule_info_body(kind: str) -> str:
    """Метаданные действующей записи; версия и дата — исходное ИнформацияОПравилах."""
    # БСП: ПравилаДляОбменаДанными.xml:184, 232, 424, 520, 568, 1134 —
    # ИмяМакетаПравил, ИмяМакетаПравилКорреспондента, ИмяФайлаПравил,
    # ИнформацияОПравилах, ИсточникПравил, ПравилаЗагружены.
    # БСП: ПравилаДляОбменаДанными/ManagerModule:320 — МакетКонфигурации;
    # 794–809 — один флаг и сведения для конвертации и её корреспондента.
    template = "ИмяМакетаПравилКорреспондента" if kind == "correspondent" else "ИмяМакетаПравил"
    return f"""Данные = Новый Структура("present", З.Выбран());
        Если З.Выбран() Тогда
        Данные.Вставить("source", Строка(З.ИсточникПравил));
        Данные.Вставить("template", З.{template});
        Данные.Вставить("file", З.ИмяФайлаПравил);
        Данные.Вставить("loaded", З.ПравилаЗагружены);
        Данные.Вставить("info", Строка(З.ИнформацияОПравилах)); КонецЕсли;"""


def rule_description(info: dict[str, Any]) -> str:
    """Не скрывает источники-менеджеры и незагруженные записи."""
    if not info["present"]:
        return "нет записи в регистре"
    return (
        f"источник={text_line(info['source'])}, макет={text_line(info['template']) or '—'}, "
        f"файл={text_line(info['file']) or '—'}, загружены={'да' if info['loaded'] else 'нет'}, "
        f"сведения={text_line(info['info']) or '—'}"
    )


def require_ok(server: DataServer, code: str) -> None:
    """Мутация должна вернуть ровно OK, без произвольного успешного хвоста."""
    if server.run(code).strip():
        raise ExchangeCheckError("неожиданный ответ стадии")
