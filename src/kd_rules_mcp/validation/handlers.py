ALGORITHM_EVENT = "Текст"
_FILE_STEM_LIMIT = 120


@dataclass(frozen=True, slots=True)
class HandlerLocation:
    """Строка файла, попавшая в тело обработчика."""

    address: str
    event: str
    # Номер строки внутри текста обработчика, с 1.
    line: int


@dataclass(frozen=True, slots=True)
class HandlerFile:
    """Файл-обёртка и диапазон тела в карте строк.

    ``line_offset`` — вычитаемое: номер строки внутри обработчика равен
    ``строка файла - line_offset``. Диапазон ``body_start``…``body_end`` включительный.
    """

    path: Path
    address: str
    event: str
    body_start: int
    body_end: int
    line_offset: int

    @property
    def name(self) -> str:
        """Имя файла без каталога."""
        return self.path.name


@dataclass(frozen=True, slots=True)
class HandlerExport:
    """Файлы одной выгрузки и карта строк.

    ``removed`` — имена прежних обёрток этой папки, которых в новой выгрузке нет.
    Файл, удалённый и сразу записанный под тем же именем, сюда не входит.
    """

    files: tuple[HandlerFile, ...]
    removed: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class Handler:
    """Непустой обработчик или алгоритм: адрес, событие, текст и имя процедуры-обёртки."""

    address: str
    event: str
    text: str
    procedure: str
    params: str
    file_prefix: str


def export_handlers(rules: ExchangeRules, out_dir: Path) -> HandlerExport:
    """Пишет непустые обработчики и алгоритмы в ``out_dir`` и возвращает карту строк.

    Пустой текст (пробелы и переводы строк) файл не даёт. Перед записью из папки удаляются
    ``*.bsl`` верхнего уровня, оставшиеся от прежней выгрузки: файл после BOM UTF-8 начинается
    со строк ``_MODULE_VARIABLES``. Чужие файлы — не ``.bsl``, ``.bsl`` с другим началом,
    файлы в подпапках и нечитаемые — не удаляются и не изменяются. Обёртка, которая снова
    попадает в выгрузку, перезаписывается и в ``removed`` не входит.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    previous = [path.name for path in _own_wrappers(out_dir)]
    for name in previous:
        (out_dir / name).unlink()
    used: set[str] = set()
    files = tuple(_write(out_dir, item, used) for item in collect_handlers(rules))
    written = {item.name for item in files}
    removed = tuple(sorted(name for name in previous if name not in written))
    return HandlerExport(files, removed)


def _own_wrappers(out_dir: Path) -> list[Path]:
    """``.bsl`` верхнего уровня, записанные прежней выгрузкой."""
    return [
        path
        for path in out_dir.iterdir()
        if path.is_file() and path.suffix.lower() == ".bsl" and _is_own_wrapper(path)
    ]


def _is_own_wrapper(path: Path) -> bool:
    """Файл нашей выгрузки: после BOM UTF-8 идут объявления переменных модуля.

    Ошибка чтения или декодирования — файл чужой.
    """
    try:
        text = path.read_text(encoding="utf-8-sig")
    except (OSError, UnicodeError):
        return False
    head = tuple(text.splitlines()[: len(_MODULE_VARIABLES)])
    return head == _MODULE_VARIABLES


def locate(export: HandlerExport, file_name: str, line: int) -> HandlerLocation | None:
    """Адрес, событие и строка внутри обработчика для строки файла.

    Строки вне тела (объявления, заголовок процедуры, общие процедуры) и неизвестный
    файл дают ``None``. ``line`` — номер строки файла с 1.
    """
    wanted = Path(file_name).name
    for item in export.files:
        if item.path.name != wanted:
            continue
        if item.body_start <= line <= item.body_end:
            return HandlerLocation(item.address, item.event, line - item.line_offset)
        return None
    return None


def collect_handlers(rules: ExchangeRules) -> list[Handler]:
    """Непустые обработчики и алгоритмы в порядке файла; модель правил не изменяет."""
    found: list[Handler] = []
    _add_node(found, rules.root, "exchange_rules", rule_address(rules.root), "Конвертация")
    parameters = rules.root.child("Параметры")
    if parameters is not None:
        for item in parameters.items:
            if item.kind.name != "parameter":
                continue
            _add_node(found, item, "parameter", rule_address(item), "Параметры", attribute=True)
    for pko in _section(rules, "ПравилаКонвертацииОбъектов"):
        _add_node(found, pko, "pko", rule_address(pko), "ПКО")
        _add_pks(found, pko)
    for pvd in _section(rules, "ПравилаВыгрузкиДанных"):
        _add_node(found, pvd, "pvd", rule_address(pvd), "ПВД")
    for pod in _section(rules, "ПравилаОчисткиДанных"):
        _add_node(found, pod, "pod", rule_address(pod), "ПОД")
    for algorithm in _section(rules, "Алгоритмы"):
        text = _string(algorithm.values.get(ALGORITHM_EVENT))
        if not text.strip():
            continue
        procedure = _algorithm_name(algorithm.code)
        params = _string(algorithm.values.get("Параметры")).strip()
        found.append(
            Handler(
                rule_address(algorithm),
                ALGORITHM_EVENT,
                text,
                procedure,
                params,
                "Алгоритм",
            )
        )
    return found


def _section(rules: ExchangeRules, tag: str) -> list[Node]:
    """Правила раздела с раскрытием групп; раздела нет — не создаётся (в отличие от ``section``)."""
    node = rules.root.children.get(tag)
    return list(node.walk()) if node is not None else []


def _add_pks(found: list[Handler], pko: Node) -> None:
    container = pko.child("Свойства")
    if container is None:
        return
    parents: dict[str, Node] = {}
    for path, node in walk_pks(container):
        parent = parents.get(path.rsplit("/", 1)[0]) if "/" in path else None
        parents[path] = node
        kind_name = node.kind.name
        prefix = "ПКГС" if kind_name == "pks_group" else "ПКС"
        for tag, area in _events(kind_name):
            text = _string(node.values.get(tag))
            if not text.strip():
                continue
            procedure = _property_procedure(prefix, pko.code, parent, node, area)
            found.append(
                Handler(
                    pks_address(pko.code, path),
                    tag,
                    text,
                    procedure,
                    _params(area),
                    prefix,
                )
            )


def _add_node(
    found: list[Handler],
    node: Node,
    kind_name: str,
    address: str,
    prefix: str,
    *,
    attribute: bool = False,
) -> None:
    for tag, area in _events(kind_name):
        raw = node.attrs.get(tag) if attribute else node.values.get(tag)
        text = _string(raw)
        if not text.strip():
            continue
        suffix = area.split("_", 1)[1]
        code = node.code.strip()
        if kind_name == "exchange_rules":
            procedure = area
        else:
            procedure = f"{prefix}_{_required(code)}_{suffix}"
        found.append(Handler(address, tag, text, procedure, _params(area), prefix))


def _events(kind_name: str) -> list[tuple[str, str]]:
    return [(tag, area) for (kind, tag), area in EVENT_AREAS.items() if kind == kind_name]


def _property_procedure(
    prefix: str, pko_code: str, parent: Node | None, node: Node, area: str
) -> str:
    """Имя процедуры ПКС или ПКГС, как в ``ПолучитьОбработчикиПКС`` / ``…ПКГС``."""
    code = pko_code.strip()
    parts = [prefix, _required(code)]
    if parent is not None:
        parent_name = _property_label(parent, parameter=False)
        if parent_name:
            parts.append(parent_name)
    label = _property_label(node, parameter=prefix == "ПКС")
    if label:
        parts.append(label)
    parts.append(area.split("_", 1)[1])
    parts.append(_required(_string(node.values.get("Код")).strip()))
    parts.append(str(len(code)))
    return "_".join(parts)


def _property_label(node: Node, *, parameter: bool) -> str:
    """Фрагмент имени: источник, иначе приёмник; у ПКС ещё имя параметра (539–549, 655–662)."""
    for side in ("Источник", "Приемник"):
        name = _part(side_name(node, side))
        if name:
            return name
    if parameter:
        return _part(_string(node.values.get("ИмяПараметраДляПередачи")))
    return ""


def _params(area: str) -> str:
    return ", ".join(HANDLER_PARAMS[area])


def _algorithm_name(code: str) -> str:
    name = _part(code) or "Алгоритм"
    if name[0].isdigit():
        return f"_{name}"
    return name


def _required(text: str) -> str:
    return _part(text) or "_"


def _part(text: str) -> str:
    """Фрагмент идентификатора BSL: ``СокрЛП`` и замена символов вне букв, цифр и ``_``."""
    return "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in text.strip())


def _string(value: object) -> str:
    return value if isinstance(value, str) else ""


def _write(out_dir: Path, item: Handler, used: set[str]) -> HandlerFile:
    signature = f"Процедура {item.procedure}({item.params}) Экспорт".splitlines()
    body = item.text.splitlines()
    lines = [*_MODULE_VARIABLES, "", *signature, *body, "КонецПроцедуры", ""]
    for name, block in _COMMON_BLOCKS:
        if name != item.procedure:
            lines.extend(block)
            lines.append("")
    body_start = len(_MODULE_VARIABLES) + 1 + len(signature) + 1
    body_end = body_start + len(body) - 1
    stem = _unique_stem(_file_stem(item.procedure, item.file_prefix), used)
    path = out_dir / f"{stem}.bsl"
    path.write_bytes(("\r\n".join(lines) + "\r\n").encode("utf-8-sig"))
    return HandlerFile(path, item.address, item.event, body_start, body_end, body_start - 1)


def _file_stem(procedure: str, prefix: str) -> str:
    stem = procedure if procedure.startswith(prefix) else f"{prefix}_{procedure}"
    if len(stem) <= _FILE_STEM_LIMIT:
        return stem
    digest = hashlib.sha1(stem.encode("utf-8")).hexdigest()[:8]
    return f"{stem[: _FILE_STEM_LIMIT - 9]}_{digest}"


def _unique_stem(stem: str, used: set[str]) -> str:
    candidate = stem
    number = 2
    while candidate.lower() in used:
        suffix = f"_{number}"
        base = stem[: _FILE_STEM_LIMIT - len(suffix)]
        candidate = f"{base}{suffix}"
        number += 1
    used.add(candidate.lower())
    return candidate
