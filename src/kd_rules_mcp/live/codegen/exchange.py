def export_object(plan: str, node_code: str, full_name: str, ref: str) -> str:
    """Совмещённая операция для прежнего CLI; сервис имеет отдельные стадии."""

    # Внутренние тела уже экранированы; убираем только общую сериализацию/перехват.
    def body(code: str) -> str:
        return code.removeprefix("Попытка ").split(" Запись = Новый ЗаписьJSON;", 1)[0]

    return json_code(
        body(register_object(plan, node_code, full_name, ref))
        + body(export_registered(plan, node_code))
    )


def import_file(plan: str, node_code: str, path: str) -> str:
    """БСП: ОбменДаннымиСервер:5081–5097,5529 — параметры штатной загрузки.

    Процедура не возвращает результат: :5218–5224,6005–6009 допускают предупреждения;
    :10926–10938 сохраняют итог в СостоянияОбменовДанными (XML:184,322,370);
    менеджер регистра:14–23 выбирает регистр областей при разделении данных.
    """
    return json_code(f"""П = ОбменДаннымиСервер.ПараметрыОбменаДаннымиЧерезФайлИлиСтроку();
        П.ПолноеИмяФайлаСообщенияОбмена = {literal(path)};
        П.ДействиеПриОбмене = Перечисления.ДействияПриОбмене.ЗагрузкаДанных;
        П.ИмяПланаОбмена = {literal(plan)}; П.КодУзлаИнформационнойБазы = {literal(node_code)};
        ОшибкаЗагрузки = ""; Попытка
        ОбменДаннымиСервер.ВыполнитьОбменДаннымиДляУзлаИнформационнойБазыЧерезФайлИлиСтроку(П);
        Исключение ОшибкаЗагрузки = ПодробноеПредставлениеОшибки(ИнформацияОбОшибке());
        КонецПопытки;
        ИмяРегистра = ?(ОбщегоНазначения.РазделениеВключено()
        И ОбщегоНазначения.ДоступноИспользованиеРазделенныхДанных(),
        "СостоянияОбменовДаннымиОбластейДанных", "СостоянияОбменовДанными");
        Состояние = РегистрыСведений[ИмяРегистра].СоздатьМенеджерЗаписи();
        Состояние.УзелИнформационнойБазы =
        ПланыОбмена[{literal(plan)}].НайтиПоКоду({literal(node_code)});
        Состояние.ДействиеПриОбмене = П.ДействиеПриОбмене; Состояние.Прочитать();
        Итог = Строка(Состояние.РезультатВыполненияОбмена);
        Предупреждения = Состояние.РезультатВыполненияОбмена =
        Перечисления.РезультатыВыполненияОбмена.ВыполненоСПредупреждениями;
        Если Предупреждения Тогда Итог = "ВыполненоСПредупреждениями"; КонецЕсли;
        Если ОшибкаЗагрузки <> "" Тогда Итог = "Ошибка"; Предупреждения = Ложь; КонецЕсли;
        Сообщения = Новый Массив; Для Каждого С Из ПолучитьСообщенияПользователю(Истина) Цикл
        Сообщения.Добавить(С.Текст); КонецЦикла;
        Данные = Новый Структура("messages,result,warnings", Сообщения, Итог, Предупреждения);
        Данные.Вставить("error", ОшибкаЗагрузки);""")


def import_message(plan: str, node_code: str, message: bytes) -> str:
    """Совместимый генератор CLI; большие передачи сервис делает через files."""
    payload = base64.b64encode(message).decode("ascii")
    body = import_file(plan, node_code, "").removeprefix("Попытка ")
    body = body.split(" Запись = Новый ЗаписьJSON;", 1)[0]
    body = body.replace(literal(""), "ИмяФайла", 1)
    return json_code(f"""ИмяФайла = ПолучитьИмяВременногоФайла("xml");
        Base64Значение({literal(payload)}).Записать(ИмяФайла); Попытка {body}
        Исключение УдалитьФайлы(ИмяФайла); ВызватьИсключение; КонецПопытки;
        УдалитьФайлы(ИмяФайла);""")


def query_rows(text: str, limit: int | None = None) -> str:
    if limit is not None and (type(limit) is not int or limit < 0):
        raise ValueError("лимит строк должен быть неотрицательным целым")
    add = "Строки.Добавить(Значения);"
    if limit is not None:
        add = f"Если Строки.Количество() < {limit} Тогда {add} КонецЕсли;"
    return json_code(f"""З = Новый Запрос({literal(text)}); Т = З.Выполнить().Выгрузить();
        Строки = Новый Массив; Имена = Новый Массив;
        Для Каждого К Из Т.Колонки Цикл Имена.Добавить(К.Имя); КонецЦикла;
        Для Каждого С Из Т Цикл Значения = Новый Массив;
        Для Каждого К Из Т.Колонки Цикл Значения.Добавить(Строка(С[К.Имя])); КонецЦикла;
        {add}
        КонецЦикла; Данные = Новый Структура("count,columns,rows",
        Т.Количество(), Имена, Строки);""")
