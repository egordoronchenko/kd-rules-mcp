def nodes_code(plan: str) -> str:
    """БСП: ОбщиеНастройкиУзловИнформационныхБаз/ManagerModule:451–467.

    Изменения читаются по таблице объекта, как exchange_check.registration_code,
    а не по несуществующей таблице ПланОбмена.<план>.Изменения.
    """
    return json_code(f"""Менеджер = ПланыОбмена[{literal(plan)}]; Узлы = Новый Массив;
        Этот = Менеджер.ЭтотУзел(); Выборка = Менеджер.Выбрать();
        Пока Выборка.Следующий() Цикл
        Узел = Выборка.Ссылка; Количество = 0; РегистрацииПоТаблицам = Новый Соответствие;
        Если Узел <> Этот Тогда
        Для Каждого Элемент Из Метаданные.ПланыОбмена[{literal(plan)}].Состав Цикл
        Запрос = Новый Запрос("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Число ИЗ "
        + Элемент.Метаданные.ПолноеИмя() + ".Изменения ГДЕ Узел = &Узел");
        Запрос.УстановитьПараметр("Узел", Узел); В = Запрос.Выполнить().Выбрать();
        Если В.Следующий() И В.Число > 0 Тогда
        РегистрацииПоТаблицам.Вставить(Элемент.Метаданные.ПолноеИмя(), В.Число);
        Количество = Количество + В.Число; КонецЕсли;
        КонецЦикла; КонецЕсли;
        Узлы.Добавить(Новый Структура(
        "code,name,this,sent,received,ready,registrations,registration_tables",
        СокрЛП(Выборка.Код), Выборка.Наименование, Узел = Этот,
        Выборка.НомерОтправленного, Выборка.НомерПринятого,
        РегистрыСведений.ОбщиеНастройкиУзловИнформационныхБаз.НастройкаЗавершена(Узел),
        Количество, РегистрацииПоТаблицам)); КонецЦикла;
        Данные = Новый Структура("enabled,nodes",
        ПолучитьФункциональнуюОпцию("ИспользоватьСинхронизациюДанных"), Узлы);""")


