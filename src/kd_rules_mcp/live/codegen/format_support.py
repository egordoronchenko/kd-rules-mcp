"""Что база знает об объектах формата корреспондента: только чтение."""

from kd_rules_mcp.live.response import json_code, literal


def format_support_code(plan: str, node: str | None = None) -> str:
    """Узлы плана, кроме этого, их версия формата и таблица корреспондента.

    БСП: ОбменДаннымиXDTOСервер:2971–3013 — `ПоддерживаемыеОбъектыФорматаКорреспондента`
    (без настроек корреспондента — зеркало своего состава, при незавершённой настройке —
    пустая таблица); 2976 — настройка «ПоддерживаемыеОбъекты» регистра
    `НастройкиОбменаДаннымиXDTO`; ОбменДаннымиПовтИсп:430–436 — `ЭтоПланОбменаXDTO`;
    плана нет в метаданных — `exists: false`.
    """
    selected = (
        f"Если СокрЛП(Выборка.Код) <> {literal(node)} Тогда Продолжить; КонецЕсли;" if node else ""
    )
    return json_code(f"""Имя = {literal(plan)}; Узлы = Новый Массив;
        Есть = Метаданные.ПланыОбмена.Найти(Имя) <> Неопределено; ЭтоXDTO = Ложь;
        Если Есть Тогда ЭтоXDTO = ОбменДаннымиПовтИсп.ЭтоПланОбменаXDTO(Имя); КонецЕсли;
        Если ЭтоXDTO Тогда Менеджер = ПланыОбмена[Имя]; Этот = Менеджер.ЭтотУзел();
        Выборка = Менеджер.Выбрать();
        Пока Выборка.Следующий() Цикл Узел = Выборка.Ссылка;
        Если Узел = Этот Тогда Продолжить; КонецЕсли; {selected}
        Настройки = РегистрыСведений.НастройкиОбменаДаннымиXDTO.ЗначениеНастройкиКорреспондента(
        Узел, "ПоддерживаемыеОбъекты");
        Таблица = ОбменДаннымиXDTOСервер.ПоддерживаемыеОбъектыФорматаКорреспондента(
        Узел, "ОтправкаПолучение");
        Строки = Новый Массив;
        Для Каждого С Из Таблица Цикл
        Строки.Добавить(Новый Структура("version,object,send,receive",
        С.Версия, С.Объект, С.Отправка, С.Получение)); КонецЦикла;
        Узлы.Добавить(Новый Структура(
        "code,name,format_version,settings_received,setup_complete,objects",
        СокрЛП(Выборка.Код), Выборка.Наименование, Выборка.ВерсияФорматаОбмена,
        Настройки <> Неопределено, ОбменДаннымиСервер.НастройкаСинхронизацииЗавершена(Узел),
        Строки)); КонецЦикла; КонецЕсли;
        Данные = Новый Структура("exists,xdto,nodes", Есть, ЭтоXDTO, Узлы);""")
