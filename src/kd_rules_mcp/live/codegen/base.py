"""Паспорт базы и планов обмена: только чтение, один ответ JSON."""

from kd_rules_mcp.live.response import json_code, literal


def _section(name: str, body: str) -> str:
    return f'''Попытка {body} Исключение
        Данные.Вставить("{name}_error", КраткоеПредставлениеОшибки(ИнформацияОбОшибке()));
        КонецПопытки;'''


def base_check_code(plans: list[str] | None) -> str:
    """Изолирует ошибки разделов и отдельных планов; ошибка раздела не прерывает остальные."""
    body = "Данные = Новый Структура;"
    body += _section(
        "connection", 'Данные.Вставить("connection", СтрокаСоединенияИнформационнойБазы());'
    )
    body += _section(
        "configuration",
        """Данные.Вставить("configuration",
        Новый Структура("name,synonym,version",
        Метаданные.Имя, Метаданные.Синоним, Метаданные.Версия));""",
    )
    # Новый X() не цепляется к свойству в одном выражении: платформа не компилирует такой код.
    body += _section(
        "platform",
        """СведенияСистемы = Новый СистемнаяИнформация;
        Данные.Вставить("platform", СведенияСистемы.ВерсияПриложения);""",
    )
    # Пользователь сеанса: функции глобального контекста, без записи; без списка пользователей — "".
    body += _section(
        "user",
        """Данные.Вставить("user",
        Новый Структура("name,full_name", ИмяПользователя(), ПолноеИмяПользователя()));""",
    )
    # Универсальная обработка — по метаданным, без создания объекта: ручной обмен и режим,
    # где ПОД выполняются.
    body += _section(
        "universal_xml",
        """Данные.Вставить("universal_xml",
        Метаданные.Обработки.Найти("УниверсальныйОбменДаннымиXML") <> Неопределено);""",
    )
    # БСП: СтандартныеПодсистемыСервер:167–171 — версия библиотеки.
    body += _section(
        "bsp", 'Данные.Вставить("bsp", СтандартныеПодсистемыСервер.ВерсияБиблиотеки());'
    )
    # Метаданные.РасширенияКонфигурации() в базе нет («Метод объекта не обнаружен»); менеджер
    # РасширенияКонфигурации отдаёт все расширения с признаком Активно.
    body += _section(
        "extensions",
        """Расширения = Новый Массив;
        Для Каждого Р Из РасширенияКонфигурации.Получить() Цикл
        Расширения.Добавить(Новый Структура("name,version,active", Р.Имя, Р.Версия, Р.Активно));
        КонецЦикла;
        Данные.Вставить("extensions", Расширения);""",
    )
    if plans is None:
        # БСП: ОбменДаннымиПовтИсп:226–230 — все подключённые планы без версий формата.
        names = 'Имена = ОбменДаннымиПовтИсп.ПланыОбменаБСП(); Данные.Вставить("all", Истина);'
    else:
        names = "Имена = Новый Массив;"
        names += "".join(f"Имена.Добавить({literal(name)});" for name in plans)
    # БСП: ОбменДаннымиПовтИсп:226–230 — подключение плана к подсистеме.
    connected = (
        'П.Вставить("bsp", ОбменДаннымиПовтИсп.ПланыОбменаБСП().Найти(Имя) <> Неопределено);'
    )
    # БСП: ОбменДаннымиПовтИсп:430–437 — технология подключённого плана.
    technology = 'П.Вставить("xdto", ОбменДаннымиПовтИсп.ЭтоПланОбменаXDTO(Имя));'
    # БСП: ОбменДаннымиПовтИсп:406–410 — РИБ; не XDTO и не РИБ — правила КД 2.
    technology += """Попытка П.Вставить("rib",
        ОбменДаннымиПовтИсп.ЭтоПланОбменаРаспределеннойИнформационнойБазы(Имя));
        Исключение П.Вставить("rib_error", КраткоеПредставлениеОшибки(ИнформацияОбОшибке()));
        КонецПопытки;"""
    # БСП: ОбменДаннымиСервер:27–60,887–888 — ключи соответствия версия → модуль.
    versions = """Версии = Новый Массив;
        Для Каждого КЗ Из
        ОбменДаннымиСервер.ЗначениеНастройкиПланаОбмена(Имя, "ВерсииФорматаОбмена") Цикл
        Версии.Добавить(Строка(КЗ.Ключ)); КонецЦикла; П.Вставить("versions", Версии);"""
    # БСП: ОбменДаннымиСервер:27–60,888 — имя универсального формата.
    versions += (
        'П.Вставить("format", '
        'ОбменДаннымиСервер.ЗначениеНастройкиПланаОбмена(Имя, "ФорматОбмена"));'
    )
    body += _section(
        "plans",
        f"""Планы = Новый Массив; Данные.Вставить("plans", Планы); {names}
        Для Каждого Имя Из Имена Цикл
        П = Новый Структура("name,exists,bsp", Имя, Ложь, Ложь); Планы.Добавить(П);
        Попытка П.exists = Метаданные.ПланыОбмена.Найти(Имя) <> Неопределено;
        Если П.exists Тогда {connected} Если П.bsp Тогда {technology}
        {("Если П.xdto Тогда " + versions + " КонецЕсли;") if plans is not None else ""}
        КонецЕсли; КонецЕсли;
        Исключение П.Вставить("error", КраткоеПредставлениеОшибки(ИнформацияОбОшибке()));
        КонецПопытки; КонецЦикла;""",
    )
    return json_code(body)
