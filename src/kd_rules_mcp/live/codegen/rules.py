"""Чтение и загрузка правил БСП со ссылками на эталон."""

from kd_rules_mcp.live.response import json_code, literal

FILES = {
    "exchange": "ExchangeRules.xml",
    "correspondent": "CorrespondentExchangeRules.xml",
    "registration": "RegistrationRules.xml",
}

RECORD_KINDS = ("exchange", "registration")


def rule_record_body(plan: str, kind: str) -> str:
    """Две записи регистра: корреспондент хранится в записи конвертации."""
    # БСП: ПравилаДляОбменаДанными.xml:9 — менеджер регистра ПравилаДляОбменаДанными.
    # БСП: ПравилаДляОбменаДанными/ManagerModule:207–221, 276–285 —
    # регистр, ИмяПланаОбмена, ВидПравил, ВидыПравилДляОбменаДанными,
    # ПравилаКонвертацииОбъектов / ПравилаРегистрацииОбъектов.
    if kind not in ("exchange", "correspondent", "registration"):
        raise ValueError("неизвестный вид правил")
    enum = "ПравилаРегистрацииОбъектов" if kind == "registration" else "ПравилаКонвертацииОбъектов"
    return f"""З = РегистрыСведений.ПравилаДляОбменаДанными.СоздатьМенеджерЗаписи();
        З.ИмяПланаОбмена = {literal(plan)};
        З.ВидПравил = Перечисления.ВидыПравилДляОбменаДанными.{enum}; З.Прочитать();"""


def rule_info_body(kind: str) -> str:
    """Метаданные действующей записи; версия и дата — исходное ИнформацияОПравилах."""
    # БСП: ПравилаДляОбменаДанными.xml:184, 232, 424, 520, 568, 1134 —
    # ИмяМакетаПравил, ИмяМакетаПравилКорреспондента, ИмяФайлаПравил,
    # ИнформацияОПравилах, ИсточникПравил, ПравилаЗагружены.
    # БСП: ПравилаДляОбменаДанными/ManagerModule:320 — МакетКонфигурации;
    # 794–809 — один флаг и сведения для конвертации и её корреспондента.
    # БСП: ПравилаДляОбменаДанными.xml:1088,1132 — флаги являются Реквизитами,
    # в том числе ПравилаЗагружены; ManagerModule:348,837,872 читает этот флаг.
    template = "ИмяМакетаПравилКорреспондента" if kind == "correspondent" else "ИмяМакетаПравил"
    return f"""Данные = Новый Структура("present", З.Выбран());
        Если З.Выбран() Тогда
        Данные.Вставить("source", Строка(З.ИсточникПравил));
        Данные.Вставить("template", З.{template});
        Данные.Вставить("file", З.ИмяФайлаПравил);
        Данные.Вставить("loaded", З.ПравилаЗагружены);
        Данные.Вставить("info", Строка(З.ИнформацияОПравилах));
        СнимокЗаписи = Новый Структура;
        Для Каждого Ресурс Из Метаданные.РегистрыСведений.ПравилаДляОбменаДанными.Ресурсы Цикл
        СнимокЗаписи.Вставить(Ресурс.Имя, З[Ресурс.Имя]); КонецЦикла;
        Для Каждого Реквизит Из Метаданные.РегистрыСведений.ПравилаДляОбменаДанными.Реквизиты Цикл
        СнимокЗаписи.Вставить(Реквизит.Имя, З[Реквизит.Имя]); КонецЦикла;
        ХешЗаписи = Новый ХешированиеДанных(ХешФункция.SHA256);
        ХешЗаписи.Добавить(ПолучитьДвоичныеДанныеИзСтроки(
        ЗначениеВСтрокуВнутр(СнимокЗаписи), КодировкаТекста.UTF8));
        Данные.Вставить("record_hash", Base64Строка(ХешЗаписи.ХешСумма)); КонецЕсли;"""


def binary_body(kind: str) -> str:
    """Хранилище раскрывается внутри базы; наружу уходит только запрошенная часть."""
    # БСП: ПравилаДляОбменаДанными/ManagerModule:794, 796, 804 —
    # ПравилаXML / ПравилаXMLКорреспондента; 363 — .Получить() даёт ДвоичныеДанные.
    field = "ПравилаXMLКорреспондента" if kind == "correspondent" else "ПравилаXML"
    return f"""Байты = Неопределено;
        Если З.{field} <> Неопределено Тогда Байты = З.{field}.Получить(); КонецЕсли;
        Данные.Вставить("binary", Байты <> Неопределено);
        Если Байты <> Неопределено Тогда
        Хеш = Новый ХешированиеДанных(ХешФункция.SHA256); Хеш.Добавить(Байты);
        Отпечаток = Base64Строка(Хеш.ХешСумма);
        Текст64 = СтрЗаменить(СтрЗаменить(Base64Строка(Байты), Символы.ПС, ""),
        Символы.ВК, "");
        Данные.Вставить("size", Байты.Размер());
        Данные.Вставить("length", СтрДлина(Текст64));
        Данные.Вставить("hash", Отпечаток); КонецЕсли;"""


def metadata_code(plan: str, kind: str) -> str:
    return json_code(
        rule_record_body(plan, kind)
        + rule_info_body(kind)
        + f"Если З.Выбран() Тогда {binary_body(kind)} КонецЕсли;"
    )


def chunk_code(plan: str, kind: str, offset: int, size: int, digest: str) -> str:
    if offset < 0 or size <= 0:
        raise ValueError("неверная граница части")
    return json_code(
        rule_record_body(plan, kind)
        + f"""Если Не З.Выбран() Тогда ВызватьИсключение "Запись правил исчезла"; КонецЕсли;
        Данные = Новый Структура; {binary_body(kind)}
        Если Не Данные.binary Тогда ВызватьИсключение "XML правил исчез"; КонецЕсли;
        Если Отпечаток <> {literal(digest)} Тогда
        ВызватьИсключение "Правила изменились во время чтения"; КонецЕсли;
        Данные = Новый Структура("chunk,hash", Сред(Текст64, {offset + 1}, {size}), Отпечаток);"""
    )


def record_snapshot_code(
    plan: str, kind: str, expected_record_hash: str, *, offset: int | None = None, size: int = 48000
) -> str:
    """Все ресурсы, включая ХранилищеЗначения, в родном строковом представлении 1С.

    JSON ресурсов читается частями; fingerprint записи проверяется в каждом вызове.
    """
    if kind not in RECORD_KINDS or (offset is not None and (offset < 0 or size <= 0)):
        raise ValueError("неверный вид записи или граница части")
    result = """Данные = Новый Структура("size,length,hash", БайтыСнимка.Размер(),
        СтрДлина(Текст64), ОтпечатокСнимка);"""
    if offset is not None:
        result = f"""Данные = Новый Структура("chunk,hash",
            Сред(Текст64, {offset + 1}, {size}), ОтпечатокСнимка);"""
    return json_code(
        rule_record_body(plan, kind)
        + rule_info_body(kind)
        + f"""
        Если Не З.Выбран() Тогда ВызватьИсключение "Запись снимка исчезла"; КонецЕсли;
        Если Данные.record_hash <> {literal(expected_record_hash)} Тогда
        ВызватьИсключение "Запись изменилась во время снятия ресурсов"; КонецЕсли;
        СнимокРесурсов = Новый Структура;
        Для Каждого Ресурс Из Метаданные.РегистрыСведений.ПравилаДляОбменаДанными.Ресурсы Цикл
        СнимокРесурсов.Вставить(Ресурс.Имя, ЗначениеВСтрокуВнутр(З[Ресурс.Имя])); КонецЦикла;
        СнимокРеквизитов = Новый Структура;
        Для Каждого Реквизит Из Метаданные.РегистрыСведений.ПравилаДляОбменаДанными.Реквизиты Цикл
        СнимокРеквизитов.Вставить(Реквизит.Имя, ЗначениеВСтрокуВнутр(З[Реквизит.Имя])); КонецЦикла;
        ЗаписьРесурсов = Новый ЗаписьJSON; ЗаписьРесурсов.УстановитьСтроку();
        ЗаписатьJSON(ЗаписьРесурсов, Новый Структура("resources,attributes",
        СнимокРесурсов, СнимокРеквизитов));
        БайтыСнимка = ПолучитьДвоичныеДанныеИзСтроки(
        ЗаписьРесурсов.Закрыть(), КодировкаТекста.UTF8);
        ХешСнимка = Новый ХешированиеДанных(ХешФункция.SHA256); ХешСнимка.Добавить(БайтыСнимка);
        ОтпечатокСнимка = Base64Строка(ХешСнимка.ХешСумма);
        Текст64 = СтрЗаменить(СтрЗаменить(Base64Строка(БайтыСнимка),
        Символы.ПС, ""), Символы.ВК, "");
        {result}"""
    )


def restore_file_code(plan: str, path: str) -> str:
    """Восстанавливает ресурсы и реквизиты записей; отсутствовавшие записи удаляет."""
    return json_code(f"""Чтение = Новый ЧтениеJSON;
        Байты = Новый ДвоичныеДанные({literal(path)});
        Чтение.УстановитьСтроку(ПолучитьСтрокуИзДвоичныхДанных(Байты, КодировкаТекста.UTF8));
        Манифест = ПрочитатьJSON(Чтение, Истина); Чтение.Закрыть();
        Если Манифест["schema"] <> "kd2-live-register/2" Тогда
        ВызватьИсключение "Нужен новый снимок с реквизитами регистра"; КонецЕсли;
        Записи = Новый Массив; Наличие = Новый Массив;
        Для Каждого Вид Из СтрРазделить("exchange,registration", ",") Цикл
        Сведения = Манифест["records"][Вид];
        З = РегистрыСведений.ПравилаДляОбменаДанными.СоздатьМенеджерЗаписи();
        З.ИмяПланаОбмена = {literal(plan)};
        З.ВидПравил = ?(Вид = "exchange",
        Перечисления.ВидыПравилДляОбменаДанными.ПравилаКонвертацииОбъектов,
        Перечисления.ВидыПравилДляОбменаДанными.ПравилаРегистрацииОбъектов);
        Если Сведения["present"] Тогда
        ЗначенияРесурсов = Новый Структура;
        Для Каждого Ресурс Из Метаданные.РегистрыСведений.ПравилаДляОбменаДанными.Ресурсы Цикл
        ТекстЗначения = Сведения["resources"][Ресурс.Имя];
        Если ТекстЗначения = Неопределено Тогда
        ВызватьИсключение "В снимке отсутствует ресурс регистра"; КонецЕсли;
        ЗначенияРесурсов.Вставить(Ресурс.Имя, ЗначениеИзСтрокиВнутр(ТекстЗначения)); КонецЦикла;
        Если ЗначенияРесурсов.Количество() <> Сведения["resources"].Количество() Тогда
        ВызватьИсключение "Состав ресурсов снимка отличается от регистра"; КонецЕсли;
        ЧислоРеквизитов = 0;
        Для Каждого Реквизит Из Метаданные.РегистрыСведений.ПравилаДляОбменаДанными.Реквизиты Цикл
        ТекстЗначения = Сведения["attributes"][Реквизит.Имя];
        Если ТекстЗначения = Неопределено Тогда
        ВызватьИсключение "В снимке отсутствует реквизит регистра"; КонецЕсли;
        ЗначенияРесурсов.Вставить(Реквизит.Имя, ЗначениеИзСтрокиВнутр(ТекстЗначения));
        ЧислоРеквизитов = ЧислоРеквизитов + 1; КонецЦикла;
        Если ЧислоРеквизитов <> Сведения["attributes"].Количество() Тогда
        ВызватьИсключение "Состав реквизитов снимка отличается от регистра"; КонецЕсли;
        ЗаполнитьЗначенияСвойств(З, ЗначенияРесурсов); КонецЕсли;
        Записи.Добавить(З); Наличие.Добавить(Сведения["present"]); КонецЦикла;
        НачатьТранзакцию(); Попытка
        Для Индекс = 0 По Записи.Количество() - 1 Цикл
        Если Наличие[Индекс] Тогда Записи[Индекс].Записать();
        Иначе Записи[Индекс].Удалить(); КонецЕсли; КонецЦикла;
        ОбменДаннымиСлужебный.СброситьКэшМеханизмаРегистрацииОбъектов();
        ЗафиксироватьТранзакцию();
        Исключение ОтменитьТранзакцию(); ВызватьИсключение; КонецПопытки;
        Данные = Новый Структура("restored", Истина);""")


def load_file_code(
    plan: str,
    path: str,
    file_name: str,
    *,
    write: bool,
    full_set: bool = True,
    include_description: bool = True,
    accept_version_mismatch: bool = False,
    report_errors: bool = False,
) -> str:
    """БСП: ПравилаДляОбменаДанными/ManagerModule:419–630, 632–822.

    Два XML используют ЗагрузитьПравила с ЭтоАрхив; три — ЗагрузитьКомплектПравил.
    Оба менеджера проверяются до первой записи, запись пары — транзакцией.
    report_errors сохраняет диагностику исключения в JSON сервера; CLI сохраняет префикс ОШИБКА.
    """
    kinds = "ПравилаКонвертацииОбъектов"
    if full_set:
        kinds += ",ПравилаРегистрацииОбъектов"
        load = f"Рег.ЗагрузитьКомплектПравил(Отказ, Данные, Описание, Адрес, {literal(file_name)});"
        # БСП: ManagerModule:37–90,728–733; форма загрузки:287–313,688–697.
        # «Продолжить» разрешает повтор только для версии, не другой конфигурации.
        retry = (
            f"""Если ЭтоНесовпадениеВерсии Тогда Отказ = Ложь;
            Описание = Истина; {load}
            Если ТипЗнч(Описание) = Тип("Структура") Тогда Отказ = Истина; КонецЕсли;
            КонецЕсли;"""
            if accept_version_mismatch
            else ""
        )
        call = f"""Данные = Новый Структура("ЗаписьПравилКонвертации, ЗаписьПравилРегистрации",
            Записи[0], Записи[1]); Описание = Неопределено; {load}
            Если ТипЗнч(Описание) = Тип("Структура") Тогда
            Совместимость = Новый Структура("kind,text",
            Строка(Описание.ВидОшибки), Строка(Описание.ТекстОшибки));
            ЭтоНесовпадениеВерсии = Совместимость.kind = "УстаревшиеПравила"
            Или Совместимость.kind = "УстаревшаяВерсияКонфигурации";
            Отказ = Истина; {retry} КонецЕсли;"""
    else:
        # У ЗагрузитьПравила нет аргумента ОписаниеОшибки: БСП:419.
        call = f"""Описание = Неопределено;
            Рег.ЗагрузитьПравила(Отказ, Записи[0], Адрес, {literal(file_name)}, Истина);"""
    mutation = (
        """Если Успех Тогда
        НачатьТранзакцию(); Попытка
        Для Каждого З Из Записи Цикл З.Записать(); КонецЦикла;
        ОбменДаннымиСлужебный.СброситьКэшМеханизмаРегистрацииОбъектов();
        ЗафиксироватьТранзакцию();
        Исключение ОтменитьТранзакцию(); ВызватьИсключение; КонецПопытки; КонецЕсли;"""
        if write
        else ""
    )
    if report_errors:
        call = f"""Попытка {call}
            Исключение Отказ = Истина;
            ОшибкаЗагрузки = ПодробноеПредставлениеОшибки(ИнформацияОбОшибке()); КонецПопытки;"""
    # БСП: ПравилаДляОбменаДанными/ManagerModule:37–90,728–733 — проверка
    # совместимости включается только Неопределено; Картинка в структуре не JSON.
    # Форма ЗагрузитьПравилаСинхронизацииДанных:367,376; ОбменДаннымиСлужебный:138–147 — кэш.
    description = ""
    if include_description:
        description = """Если Совместимость <> Неопределено Тогда
            Сообщения.Добавить(Совместимость.text);
            ИначеЕсли Описание <> Неопределено И Описание <> Истина И Описание <> "" Тогда
            Сообщения.Добавить(Строка(Описание)); КонецЕсли;"""
    return json_code(f"""Рег = РегистрыСведений.ПравилаДляОбменаДанными;
        Записи = Новый Массив;
        Для Каждого Вид Из СтрРазделить({literal(kinds)}, ",") Цикл
        З = Рег.СоздатьМенеджерЗаписи(); З.ИмяПланаОбмена = {literal(plan)};
        З.ВидПравил = Перечисления.ВидыПравилДляОбменаДанными[Вид];
        З.ИсточникПравил = Перечисления.ИсточникиПравилДляОбменаДанными.Файл;
        Записи.Добавить(З); КонецЦикла;
        Адрес = ПоместитьВоВременноеХранилище(Новый ДвоичныеДанные({literal(path)}));
        Совместимость = Неопределено; Отказ = Ложь; ОшибкаЗагрузки = "";
        {call}
        Правила = Новый Массив; Успех = Не Отказ;
        Для Каждого З Из Записи Цикл
        Успех = Успех И З.ПравилаЗагружены;
        ВидКонвертации = З.ВидПравил =
        Перечисления.ВидыПравилДляОбменаДанными.ПравилаКонвертацииОбъектов;
        Правила.Добавить(Новый Структура("kind,loaded,info",
        ?(ВидКонвертации, "exchange", "registration"),
        З.ПравилаЗагружены, Строка(З.ИнформацияОПравилах)));
        Если ВидКонвертации Тогда
        Правила.Добавить(Новый Структура("kind,loaded,info", "correspondent",
        З.ПравилаЗагружены, Строка(З.ИнформацияОПравилах))); КонецЕсли;
        КонецЦикла;
        Сообщения = Новый Массив;
        {description}
        Для Каждого С Из ПолучитьСообщенияПользователю(Истина) Цикл
        Сообщения.Добавить(С.Текст); КонецЦикла; {mutation}
        Данные = Новый Структура("loaded,rules,messages,compatibility",
        Успех, Правила, Сообщения, Совместимость);
        Если ОшибкаЗагрузки <> "" Тогда Данные.Вставить("error", ОшибкаЗагрузки); КонецЕсли;""")
