"""Файлы на сервере базы: каждый вызов независим от серверного сеанса."""

from kd_rules_mcp.live.response import json_code, literal


def begin_file_code(extension: str = "zip") -> str:
    """Создаёт пустой файл, возвращает имя для следующих частей."""
    if extension not in ("zip", "xml", "json"):
        raise ValueError("расширение временного файла: zip, xml или json")
    return json_code(f'''ИмяФайла = ПолучитьИмяВременногоФайла("{extension}");
        Поток = Новый ФайловыйПоток(ИмяФайла, РежимОткрытияФайла.Создать); Поток.Закрыть();
        Данные = Новый Структура("path", ИмяФайла);''')


def append_chunk_code(path: str, payload: str) -> str:
    """Часть base64 декодируется отдельно; границы частей кратны четырём."""
    return json_code(f"""Поток = Новый ФайловыйПоток({literal(path)},
        РежимОткрытияФайла.Дописать); ЗаписьЧасти = Новый ЗаписьДанных(Поток);
        ЗаписьЧасти.Записать(Base64Значение({literal(payload)}));
        ЗаписьЧасти.Закрыть(); Поток.Закрыть(); Данные = Новый Структура;""")


def delete_file_code(path: str) -> str:
    return json_code(f"""Файл = Новый Файл({literal(path)});
        Удален = Ложь; Если Файл.ЭтоФайл() Тогда
        УдалитьФайлы(Файл.ПолноеИмя); Удален = Истина; КонецЕсли;
        Данные = Новый Структура("deleted", Удален);""")


def file_info_code(path: str) -> str:
    """Размер и SHA-256 именно принятого файла; каталог не читается и не удаляется."""
    return json_code(f"""Файл = Новый Файл({literal(path)});
        Размер = 0; Отпечаток = ""; ЭтоФайл = Файл.ЭтоФайл(); Если ЭтоФайл Тогда
        Байты = Новый ДвоичныеДанные(Файл.ПолноеИмя); Размер = Байты.Размер();
        Хеш = Новый ХешированиеДанных(ХешФункция.SHA256); Хеш.Добавить(Байты);
        Отпечаток = Base64Строка(Хеш.ХешСумма); КонецЕсли;
        Данные = Новый Структура("is_file,size,hash", ЭтоФайл, Размер, Отпечаток);""")
