def helper_forms(name: str, version: int | None) -> tuple[str, ...]:
    """Только подтверждённые шаблоны; старые варианты остаются непроверенными."""
    group = name.casefold() == "добавитьпктч"
    template = HELPER_PKTCH if group else HELPER_PKS
    basic = template.format(parameter="", check="")
    if version != 3:
        return (basic,)
    check = HELPER_CONDITION.format(value=" Неопределено" if group else "")
    if not group:
        check = "Если РодительПКС = Неопределено Тогда Возврат; КонецЕсли;" + check
    return (basic, template.format(parameter=', УсловиеПрименения = ""', check=check))
