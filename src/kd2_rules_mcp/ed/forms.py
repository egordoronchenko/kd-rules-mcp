def event_name(name: str) -> str | None:
    """Событие определяется полным суффиксом, а не количеством подчёркиваний."""
    if not name.casefold().startswith(("пко_", "под_", "пкс_")):
        return None
    return next(
        (event for event in EVENT_SIGNATURES if name.casefold().endswith("_" + event.casefold())),
        None,
    )


